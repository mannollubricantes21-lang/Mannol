/** Copia texto (API moderna o, si no hay, textarea + execCommand). Devuelve true si copió. */
export async function copyText(text) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {}
  try {
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.setAttribute("readonly", "");
    ta.style.cssText = "position:fixed;top:0;left:0;opacity:0;pointer-events:none";
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand("copy");
    ta.remove();
    return ok;
  } catch {
    return false;
  }
}

/** Abre WhatsApp con el texto listo (el usuario elige el chat). `phone` opcional. */
export function openWhatsApp(text, phone = "") {
  const url = `https://wa.me/${String(phone).replace(/\D/g, "")}?text=${encodeURIComponent(text)}`;
  const w = window.open(url, "_blank");
  if (w) { try { w.opener = null; } catch {} }
  else window.location.href = url; // ventana bloqueada → misma pestaña
}

