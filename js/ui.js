// v5.10.0 — Tablas que en el móvil se ven como tarjetas
// =====================================================
// Las tablas con la clase `table-cards` se dibujan como tarjetas (una por
// fila) en pantallas ≤ 640 px (CSS en mobile-ux.css §8). Aquí solo se pone a
// cada celda la etiqueta de su columna (data-label) y se marcan la celda de
// imagen, la del título y la de acciones. Funciona aunque la vista vuelva a
// dibujar la tabla (MutationObserver, se ejecuta antes de pintar).
export function labelTableCards(scope = document) {
  scope.querySelectorAll("table.table-cards").forEach((table) => {
    const labels = [];
    table.querySelectorAll("thead th").forEach((th) => {
      const txt = th.textContent.replace(/\s+/g, " ").trim();
      for (let i = 0; i < (th.colSpan || 1); i++) labels.push(txt);
    });
    if (!labels.length) return;
    const hasMedia = labels[0] === "";
    const titleIdx = hasMedia ? 1 : 0;
    const actionsIdx = /acciones/i.test(labels[labels.length - 1]) ? labels.length - 1 : -1;
    table.querySelectorAll(":scope > tbody > tr, :scope > tfoot > tr").forEach((tr) => {
      if (tr.dataset.tc === "1") return;
      let col = 0;
      for (const cell of tr.children) {
        const span = cell.colSpan || 1;
        if (cell.tagName === "TD") {
          if (span > 1) cell.classList.add("tc-full");
          else {
            cell.dataset.label = labels[col] ?? "";
            if (hasMedia && col === 0) cell.classList.add("tc-media");
            else if (col === titleIdx) cell.classList.add("tc-title");
            if (col === actionsIdx) cell.classList.add("tc-actions");
            // v5.11.0: en móvil los datos van en una cuadrícula de 4 columnas según su
            // largo: cortos = 1 columna, medianos = 2, largos = todo el ancho. La etiqueta
            // va en MAYÚSCULAS (más ancha): con más de 8 letras ya no cabe en 1 columna.
            else if (col !== titleIdx && !(hasMedia && col === 0)) {
              const len = cell.textContent.replace(/\s+/g, " ").trim().length;
              const lab = (labels[col] || "").length;
              cell.classList.add(len > 24 || lab > 20 ? "tc-wide" : len > 8 || lab > 8 ? "tc-half" : "tc-short");
            }
          }
        }
        col += span;
      }
      if (hasMedia) tr.classList.add("tc-has-media");
      tr.dataset.tc = "1";
    });
    table.parentElement?.classList.add("tc-wrap");
  });
}

export function setupTableCards(root) {
  if (!root || root.__tableCards) return;
  labelTableCards(root);
  let queued = false;
  const obs = new MutationObserver(() => {
    if (queued) return;
    queued = true;
    queueMicrotask(() => { queued = false; labelTableCards(root); });
  });
  obs.observe(root, { childList: true, subtree: true });
  root.__tableCards = obs;
}

